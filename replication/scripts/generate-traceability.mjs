import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const raiz=resolve(new URL('..',import.meta.url).pathname,'..');
const fuente=JSON.parse(await readFile(resolve(raiz,'replication/traceability/traceability.json'),'utf8'));
const campos=['requisito','patron','implementacion','prueba','resultado','amenaza','documento'];
for (const [i,fila] of fuente.entries()) for (const campo of campos) if (!fila[campo]) throw new Error(`Fila ${i+1}: falta ${campo}`);
const tabla=['# Matriz integral de trazabilidad COBRIA','',`Generada automáticamente. Filas: ${fuente.length}.`,'',
  '| Requisito | Patrón | Implementación | Prueba | Resultado | Amenaza | Documento |','|---|---|---|---|---|---|---|',
  ...fuente.map(f=>`| ${campos.map(c=>String(f[c]).replaceAll('|','\\|')).join(' | ')} |`),''].join('\n');
await writeFile(resolve(raiz,'specification/TRACEABILITY-MATRIX-AUTOGENERATED.md'),tabla);
const publico=resolve(raiz,'../COBRIA-atlas/public'); await mkdir(publico,{recursive:true});
await writeFile(resolve(publico,'trazabilidad.json'),JSON.stringify({version:'1.3',generadoEn:new Date().toISOString(),filas:fuente},null,2));
console.log(`Trazabilidad válida: ${fuente.length} requisitos.`);
